public class BitWiseOperator{
    public static void main(String args[]){
        //AND operator
        System.out.println(5 & 6);

        //OR operator
        System.out.println(5 | 6);

        //XOR operator
        System.out.println(5 ^ 6);

        //1's complement
        System.out.println(~5);
    }
}